def strip_one_underscore(name):
    return name[1:] if name.startswith('_') else name


def load_allowlist(path):
    d = json.load(open(path, encoding='utf-8'))
    funcs = list(d['summary']['allegro_family_api_names'])
    globs = list(d['shared_globals']['lib_globals_touched_by_game']['globals'].keys())
    return funcs, globs


def collect_scope(dies, canonical, cache, scope):
    cus = gi.in_scope_cus(dies, scope)
    functions = []
    globals_ = []
    for cu in cus:
        gi.collect_functions(dies, cu, canonical, cache, functions)
        gi.collect_globals(dies, cu, canonical, cache, globals_)
    return functions, globals_


def reachable_keys(items_ret_params, items_types):
    seen = set()
    nodes = {}
    for ret, params in items_ret_params:
        gi.collect_reachable(ret, seen, nodes)
        for p in params:
            gi.collect_reachable(p, seen, nodes)
    for t in items_types:
        gi.collect_reachable(t, seen, nodes)
    return nodes


def func_body(fn):
    conv = '__cdecl' if fn['calling_convention'] != 'stdcall' else '__stdcall'
    params = [gi.decl(p, '') for p in fn['params']]
    if fn['variadic']:
        params.append('...')
    paramstr = ', '.join(params) if params else ('void' if fn['prototyped'] else '')
    ret_str = gi.decl(fn['ret'], '')
    return conv, ret_str, paramstr


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dwarf', default=os.path.join(REPO_ROOT, 'artifacts', 'dwarf_info.txt'))
    ap.add_argument('--functions', default=os.path.join(REPO_ROOT, 'artifacts', 'functions.json'))
    ap.add_argument('--lib-boundary', default=os.path.join(REPO_ROOT, 'artifacts', 'lib_boundary.json'))
    ap.add_argument('--out', default=os.path.join(HERE, 'pf_lib_bindings.h'))
    ap.add_argument('--types-out', default=os.path.join(HERE, 'pf_lib_bindings_types.h'))
    ap.add_argument('--allegro-api-out',
                     default=os.path.join(REPO_ROOT, 'src', 'icytower', 'allegro_api.h'))
    ap.add_argument('--notes-out', default=os.path.join(HERE, 'LIB_BINDINGS_NOTES.md'))
    ap.add_argument('--exclude', default='',
                     help='comma-separated allow-list names to omit (an Allegro-family '
                          'function about to be compiled natively into the carrier from '
                          'src/, mirroring gen_bindings.py --exclude). Empty today: no '
                          'Allegro-family function is reimplemented in src/ yet.')
    args = ap.parse_args()

    exclude = set(n.strip() for n in args.exclude.split(',') if n.strip())

    print('parsing DWARF...', file=sys.stderr)
    dies = gi.parse_dwarf(args.dwarf)
    gi.ANON_TYPEDEF_NAMES = gi.compute_anon_typedef_names(dies)
    canonical, _conflicts = gi.compute_canonical(dies, gi.ANON_TYPEDEF_NAMES)
    cache = {}

    game_funcs, game_globals = collect_scope(dies, canonical, cache, 'game')
    game_nodes = reachable_keys(
        [(f['ret'], f['params']) for f in game_funcs],
        [g['type'] for g in game_globals])
    game_keys = set(game_nodes.keys())
    print('game-scope reachable type entities: %d (already in it_types.h)' % len(game_keys),
          file=sys.stderr)

    all_funcs, all_globals = collect_scope(dies, canonical, cache, 'all')
    coff_va_map = gi.load_coff_va_map(args.functions)
    for fn in all_funcs:
        conv, evidence = gi.calling_convention_for(fn['va'], coff_va_map)
        fn['calling_convention'] = conv
        fn['convention_evidence'] = evidence

    by_name_func = {}
    for f in all_funcs:
        by_name_func.setdefault(f['name'], []).append(f)
    by_name_glob = {}
    for g in all_globals:
        by_name_glob.setdefault(g['name'], []).append(g)

    allow_funcs_raw, allow_globs_raw = load_allowlist(args.lib_boundary)

    resolved_funcs = []
    resolved_globs = []
    unresolved = []
    ambiguous = []
    for raw in allow_funcs_raw:
        dn = strip_one_underscore(raw)
        cands = by_name_func.get(dn, [])
        if not cands:
            unresolved.append(('function', raw, dn))
            continue
        if len(cands) > 1:
            ambiguous.append(('function', raw, dn, [c['cu'] for c in cands]))
        f = dict(cands[0])
        f['raw_name'] = raw
        f['dwarf_name'] = dn
        resolved_funcs.append(f)
    for raw in allow_globs_raw:
        dn = strip_one_underscore(raw)
        cands = by_name_glob.get(dn, [])
        if not cands:
            unresolved.append(('global', raw, dn))
            continue
        if len(cands) > 1:
            ambiguous.append(('global', raw, dn, [c['cu'] for c in cands]))
        g = dict(cands[0])
        g['raw_name'] = raw
        g['dwarf_name'] = dn
        resolved_globs.append(g)

    if unresolved or ambiguous:
        sys.stderr.write(
            'gen_lib_bindings.py: lib_boundary.json allow-list does not resolve 1:1 '
            'against the scope=all DWARF model -- refusing to generate.\n'
            'unresolved: %r\nambiguous: %r\n' % (unresolved, ambiguous))
        return 1

    resolved_funcs.sort(key=lambda f: f['dwarf_name'])
    resolved_globs.sort(key=lambda g: g['dwarf_name'])

    # --- name collisions -------------------------------------------------
    reserved_collisions = [f['dwarf_name'] for f in resolved_funcs
                            if f['dwarf_name'] in gb.RESERVED_CRT_WINDOWS_IDENTS]
    reserved_collisions += [g['dwarf_name'] for g in resolved_globs
                             if g['dwarf_name'] in gb.RESERVED_CRT_WINDOWS_IDENTS]

    game_scope_names = set(f['name'] for f in game_funcs) | set(g['name'] for g in game_globals)
    game_scope_collisions = [n for n in
                              [f['dwarf_name'] for f in resolved_funcs] +
                              [g['dwarf_name'] for g in resolved_globs]
                              if n in game_scope_names]

    lib_names = [f['dwarf_name'] for f in resolved_funcs] + [g['dwarf_name'] for g in resolved_globs]
    internal_lib_collisions = [n for n in set(lib_names) if lib_names.count(n) > 1]

    inline_math_hits = sorted(UPSTREAM_INLINE_MATH_NAMES &
                               set(f['dwarf_name'] for f in resolved_funcs))

    # --- reachable types: allow-list minus game-scope ---------------------
    lib_nodes = reachable_keys(
        [(f['ret'], f['params']) for f in resolved_funcs],
        [g['type'] for g in resolved_globs])
    lib_keys = set(lib_nodes.keys())
    new_keys = lib_keys - game_keys
    print('allow-list reachable type entities: %d (%d already covered by it_types.h, %d new)' %
          (len(lib_keys), len(lib_keys) - len(new_keys), len(new_keys)), file=sys.stderr)

    order, cycle_anomalies = gi.topo_order(lib_nodes)
    opaque_reasons = []

    su_new = [k for k in order if k[0] == 'su' and k in new_keys]
    td_new = [k for k in order if k[0] == 'td' and k in new_keys]
    en_new = [k for k in lib_nodes if k[0] == 'en' and k in new_keys]

    fwd_keys = sorted(su_new, key=lambda k: lib_nodes[k]['name'])

    def emit_new_types_body():
        lines = []
        lines.append('/* forward declarations (types new to the library-scope surface) */')
        for k in fwd_keys:
            n = lib_nodes[k]
            lines.append('%s %s;' % (n['kind'], n['name']))
        lines.append('')
        lines.append('/* Win32 scalar typedefs the structs below reference. Plain, not from')
        lines.append(' * <windows.h> -- this header must never be included alongside')
        lines.append(' * <windows.h> in the same translation unit (it_types.h\'s BITMAP/')
        lines.append(' * pthread_mutex_t_ already collide with wingdi.h/pthread the same way,')
        lines.append(' * see carrier/src/bind.cpp\'s header comment; the same rule applies')
        lines.append(' * here, for the same reason).')
        lines.append(' */')
        emitted_scalar = set()
        for k in order:
            if k not in new_keys or k[0] != 'td':
                continue
            n = lib_nodes[k]
            if n['inner']['kind'] == 'base' and n['name'] in ('HANDLE', 'HCURSOR', 'HICON', 'PVOID'):
                lines.append('typedef %s;' % gi.decl(n['inner'], n['name']))
                emitted_scalar.add(k)
        lines.append('')
        lines.append('/* struct bodies + remaining typedefs, dependency order */')
        emitted_su_names = set()
        for key in order:
            if key not in new_keys or key in emitted_scalar:
                continue
            n = lib_nodes[key]
            if key[0] == 'su':
                if n['name'] in emitted_su_names:
                    continue
                emitted_su_names.add(n['name'])
                lines.extend(gi.emit_struct_body(n, opaque_reasons))
            elif key[0] == 'td':
                lines.append('typedef %s;' % gi.decl(n['inner'], n['name']))
        lines.append('')
        return '\n'.join(lines)

    types_body = emit_new_types_body()

    # ======================================================================
    # pf_lib_bindings_types.h  (carrier world type provider)
    # ======================================================================
    ts = []
    ts.append('/* pf_lib_bindings_types.h -- GENERATED FILE. DO NOT EDIT.')
    ts.append(' * Produced by carrier/gen/gen_lib_bindings.py.')
    ts.append(' * Generated: %s UTC' % datetime.datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S'))
    ts.append(' *')
    ts.append(' * Additive type provider for pf_lib_bindings.h: the %d struct/typedef' % len(new_keys))
    ts.append(' * entities reachable from the library-scope allow-list that are NOT')
    ts.append(' * already reachable from game scope (and therefore not already in')
    ts.append(' * carrier/gen/it_types.h) -- GFX_DRIVER, GFX_MODE, GFX_MODE_LIST,')
    ts.append(' * JOYSTICK_*, SYSTEM_DRIVER, _DRIVER_INFO, plus the Win32 scalar')
    ts.append(' * typedefs those structs reference. Everything else (BITMAP, FONT, RGB,')
    ts.append(' * SAMPLE, DATAFILE, PACKFILE, MIDI, PALETTE, fixed, ...) comes from the')
    ts.append(' * #include below, verbatim, never redefined here.')
    ts.append(' * Re-run gen_lib_bindings.py to regenerate; do not hand-edit.')
    ts.append(' */')
    ts.append('')
    ts.append('#ifndef PF_LIB_BINDINGS_TYPES_H')
