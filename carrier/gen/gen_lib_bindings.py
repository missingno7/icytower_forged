#!/usr/bin/env python3
"""gen_lib_bindings.py -- generate carrier/gen/pf_lib_bindings.h,
carrier/gen/pf_lib_bindings_types.h and src/icytower/allegro_api.h.

Closes notes/library_boundary.md item 13 / win32_pilot.md SS7b "NEXT": the
game-scope pf_bindings.h (carrier/gen/gen_bindings.py) binds only the 156
game-CU globals and 242 game-CU functions (interop_index.json scope=game),
so a promoted src/ function cannot yet call blit()/textout_ex()/
install_int() or read key[]/screen/font/gfx_driver by their plain upstream
names -- there is no macro for them. This script closes that gap by binding
exactly the boundary census's allow-list (artifacts/lib_boundary.json,
generated by tools_recon/lib_boundary_scan.py, described in
notes/library_boundary.md SS3): 100 Allegro-family functions the game calls
(summary.allegro_family_api_names, which already includes the 2 logg entry
points and the 4 internal-but-legitimate edges: __WinMain,
__install_allegro_version_check, __color_load_depth, __fixup_loaded_bitmap)
and 26 library globals the game reads
(shared_globals.lib_globals_touched_by_game.globals, which already includes
_win_hcursor, the one genuine internal-symbol data edge).

Like gen_bindings.py, this is NOT a second DWARF parser: it imports
carrier/gen/gen_interop.py as a module and reuses its parsed model
(parse_dwarf/compute_canonical/resolve_type/decl/emit_struct_body/
topo_order/collect_functions/collect_globals/collect_reachable/
calling_convention_for), run twice against the SAME dies/canonical/cache --
once with scope='game' (to learn what carrier/gen/it_types.h already
provides, so this script never redefines it) and once with scope='all' (to
find the allow-listed symbols, which live in Allegro/logg CUs gen_interop.py
only visits in 'all' mode -- see carrier/gen_all_test/ for a throwaway
demonstration run of that mode, INTEROP_NOTES.md's own counts: 1139
globals, 1823 functions, scope=all vs 156/242 scope=game).

Name mapping (verified, not assumed): every name in lib_boundary.json's two
lists carries the disassembly/COFF spelling, which is the upstream C
identifier plus MinGW's one leading cdecl underscore (`blit` -> `_blit`,
already-underscored internal names like `_win_hcursor` -> `__win_hcursor`).
Stripping exactly one leading underscore and looking the result up as a
DWARF DW_AT_name resolves all 126 names uniquely against the scope='all'
model with 0 missing and 0 ambiguous (checked below, and the run fails loud
if that ever stops being true) -- so "upstream public name" and "DWARF
source-level name" are the same string for this entire allow-list.

Types: everything these 126 signatures need is emitted DWARF-first from the
same parsed model. Most of it (BITMAP, FONT, RGB, SAMPLE, DATAFILE,
PACKFILE, MIDI, PALETTE, fixed, ...) is already reachable from game-scope
signatures and therefore already in carrier/gen/it_types.h; this script
computes that overlap by running collect_reachable over BOTH scopes from
the shared cache and only emits the SET DIFFERENCE (game-scope-run: 179
reachable type entities; allow-list-run: 57; new: 23 -- GFX_DRIVER,
GFX_MODE, GFX_MODE_LIST, JOYSTICK_AXIS_INFO, JOYSTICK_BUTTON_INFO,
JOYSTICK_INFO, JOYSTICK_STICK_INFO, SYSTEM_DRIVER, _DRIVER_INFO, plus the
Win32 scalar typedefs those structs reference: HANDLE, HCURSOR, HICON,
PVOID, uint64_t) into pf_lib_bindings_types.h, instead of re-emitting
it_types.h's 139 structs/unions a second time under a second name.

Inline functions (win32_pilot.md deliverable note): Allegro's fixed-point
math (fixmul, fixdiv, ftofix, fixtoi, itofix, fixtof, fixfloor, fixceil,
...) is `static inline` in allegro/inline/*.inl upstream, so a game CU that
uses it compiles the arithmetic directly into its own .text -- there is
never a distinct callee, so no such name can appear in a game-to-library
CALL EDGE census in the first place. Checked here by set intersection
against the well-known upstream inline-math names: 0 of the 100 allow-listed
function names match, which is the expected, mechanical consequence of how
the census was built (a call-edge scan), not a coincidence -- documented in
LIB_BINDINGS_NOTES.md rather than silently assumed.

Constants (KEY_*, GFX_*, DRAW_MODE_*, MASK_COLOR_*): these are C
preprocessor macros in upstream Allegro headers, not DWARF entities --
`objdump --dwarf=info` (this project's only DWARF source, see
notes/library_boundary.md) carries no macro table (that needs `-g3`
--dwarf=info,macro, not present here; checked: 0 KEY_-shaped enumerators
anywhere in the 130019-DIE dump, only 2 enums total and both are the game's
own attrb_state_t/axis). They cannot be generated from evidence this
project has, so the small set emitted into allegro_api.h below is
hand-transcribed from the public Allegro 4.4 headers instead, at two
different confidence levels the generator keeps textually distinct:
  - KEY_MAX=127 is MEASURED (key[]'s DWARF array bound, this run); the
    sequential KEY_* scancode values that number leans on are INFERRED
    from upstream keyboard.h, not measured here.
  - The DirectX/GDI GFX_* driver ids are INFERRED, but from THIS project's
    own evidence: notes/library_boundary.md SS2's driver-table dump
    (__gfx_driver_list, KNOWN, read from .data) already names the 4-letter
    tag for every driver Icy Tower links in (DXAC, DXSO, DXSA, DXWN, DXOV,
    GDIB); AL_ID(a,b,c,d) = (a<<24)|(b<<16)|(c<<8)|d is a stable Allegro
    macro unchanged since Allegro 3, so those constants are computed from
    already-measured tags, not recalled as bare numbers.
  - DRAW_MODE_*, MASK_COLOR_*, GFX_AUTODETECT/_FULLSCREEN/_WINDOWED/_SAFE/
    _TEXT are INFERRED from public Allegro 4.4 documentation with no
    project-specific corroboration; flagged as such in LIB_BINDINGS_NOTES.md.

Outputs:
  carrier/gen/pf_lib_bindings.h        one #define per allow-listed name,
                                        binding it to its original address
                                        (game-scope pf_bindings.h's sibling,
                                        library scope instead of game scope)
  carrier/gen/pf_lib_bindings_types.h  the additive (game-scope-it_types.h-
                                        minus) type provider pf_lib_bindings.h
                                        needs
  src/icytower/allegro_api.h           address-free declarations in upstream
                                        spelling: this port's stand-in for
                                        <allegro.h> until src/ takes a real
                                        Allegro dependency (win32_pilot.md
                                        SS4 option (A)); must pass
                                        scripts/check_native_layer.py
  carrier/gen/LIB_BINDINGS_NOTES.md    counts, collisions, the constants'
                                        evidence labels, the standalone-swap
                                        plan

Refuses to bind anything outside the allow-list (win32_pilot.md SS7b item 2
-- "the generator must refuse any name outside the inventory"): the only
source of names read by this script is lib_boundary.json's two lists;
nothing here re-derives or widens that set.
"""
