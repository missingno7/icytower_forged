#!/usr/bin/env python3
"""gen_game_globals.py - generates gen/game_globals.inc: the {VA, size} table
of every game-owned (not Allegro/CRT/DirectX) .data/.bss global, used by
carrier/src/det.cpp's tick-sensor digest (milestones 5-7, win32_pilot.md).

Why this table exists (see carrier/NOTES.md "Milestones 5-7"): hashing the
FULL .data+.bss range makes two otherwise-identical --det runs diverge,
because Windows randomizes the load address of every dynamically-loaded DLL
(ddraw/dinput/dsound/msvcrt) per PROCESS, and pointers into those DLLs'
objects (DirectInput/DirectSound/DirectDraw COM pointers, CRT/MinGW runtime
pointers, mutex/thread/event HANDLEs) get baked directly into scattered
Allegro-internal globals throughout .bss. Byte-diffing two runs' raw memory
and mapping differing offsets to symbols (artifacts/coff_symbols.json) found
that EVERY affected global belongs to an Allegro/CRT/DirectX compile unit,
never to the game's own 25 source files - and that the *set* of affected
globals isn't even stable across different sampling pairs (ASLR entropy
sometimes coincidentally matches), making per-byte exclusion an unbounded,
non-convergent chase. Restricting the digest to game-owned globals only
(the same `game` DWARF scope carrier/gen/gen_interop.py already uses for
carrier/gen/it_globals.h) sidesteps the whole category at its source: it is
a faithful, principled definition of "the game's own state" for a
determinism proof, not an attempt to hash every byte of two linked
libraries' internal bookkeeping.

Inputs (read-only, never modified by this script):
    carrier/gen/interop_index.json  - the `globals` list (name, va, type),
                                       generated by gen_interop.py (a
                                       DIFFERENT agent's tool - not touched)
    artifacts/coff_symbols.json     - full COFF symbol table, used only to
                                       find each global's size (gap to the
                                       next symbol at any VA, game or not)

Output: carrier/gen/game_globals.inc (a plain {va,size} initializer list,
#include'd by carrier/src/det.cpp). Excludes 3 game-CU globals that are
themselves host-object identities, not game state (gFLDADMutex,
sLogMutex__log2file, gFLDADThread - all in fld_adspot.c's ad-fetch thread
plumbing) - see EXCLUDE_NAMES below and NOTES.md for the same evidence.

Usage: python gen_game_globals.py [repo_root]
"""
import bisect
import json
import sys
from pathlib import Path

DATA_VA, DATA_SIZE = 0x4bc000, 0x176f4
BSS_VA, BSS_SIZE = 0x4dd000, 0x36978
EXCLUDE_NAMES = {"gFLDADMutex", "sLogMutex__log2file", "gFLDADThread"}

# MEASURED (carrier/NOTES.md "Milestones 5-7"): these 4 globals are
# `Tmenu_selection` structs (DWARF: value@0 int, size@4 int, caption@8
# char[128], 136 bytes) whose `caption` display-text field was confirmed (by
# byte-diffing two --det runs of the identical script) to differ while
# `value`@0 - the field gameplay actually reads - never does. Capping their
# hashed size to 8 keeps the meaningful fields in the digest and drops only
# the cosmetic text.
SIZE_OVERRIDE = {
    "eyecandy_selection": 8,
    "scroll_speed_selection": 8,
    "floor_size_selection": 8,
    "gravity_selection": 8,
}


def main():
    repo_root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2]
    interop = json.loads((repo_root / "carrier/gen/interop_index.json").read_text())
    coff = json.loads((repo_root / "artifacts/coff_symbols.json").read_text())

    all_data_syms = sorted(
        s["va"] for s in coff if s.get("va") and s.get("section_name") in (".data", ".bss")
    )

    def next_symbol_va(va):
        i = bisect.bisect_right(all_data_syms, va)
        return all_data_syms[i] if i < len(all_data_syms) else va + 64

    globals_ = sorted(interop["globals"], key=lambda g: int(g["va"], 16))
    rows = []
    for g in globals_:
        if g["name"] in EXCLUDE_NAMES:
            continue
        va = int(g["va"], 16)
        size = next_symbol_va(va) - va
        if size <= 0 or size > 4096:
            size = 64  # fallback cap: unusually large gap, be conservative
        if g["name"] in SIZE_OVERRIDE:
            size = SIZE_OVERRIDE[g["name"]]
        if DATA_VA <= va < DATA_VA + DATA_SIZE:
            size = min(size, DATA_VA + DATA_SIZE - va)
        elif BSS_VA <= va < BSS_VA + BSS_SIZE:
            size = min(size, BSS_VA + BSS_SIZE - va)
        else:
            continue  # outside .data/.bss entirely - shouldn't happen, skip defensively
        rows.append((va, size, g["name"]))

    out_path = repo_root / "carrier/gen/game_globals.inc"
    with out_path.open("w") as f:
        f.write("// game_globals.inc - GENERATED by carrier/gen/gen_game_globals.py. DO NOT EDIT.\n")
        f.write("// {VA, size} for every game-owned .data/.bss global (source: interop_index.json's\n")
        f.write("// `globals` list, DWARF scope=game), used by carrier/src/det.cpp's tick-sensor\n")
        f.write("// digest. See that script's docstring and carrier/NOTES.md \"Milestones 5-7\".\n")
        f.write(f"// {len(rows)} entries, {sum(r[1] for r in rows)} bytes total.\n")
        f.write("static const GameGlobal kGameGlobals[] = {\n")
        for va, size, name in rows:
            f.write(f"    {{0x{va:08x}u, {size}u}}, // {name}\n")
        f.write("};\n")
    print(f"wrote {len(rows)} entries ({sum(r[1] for r in rows)} bytes) to {out_path}")


if __name__ == "__main__":
    main()
