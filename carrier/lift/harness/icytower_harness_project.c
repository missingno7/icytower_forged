/* icytower_harness_project.c -- Icy Tower's own per-function dispatch for
 * the offline harness's macro-bound world, SRC form.
 *
 * Implements pf_harness_dispatch_src() (port_forge/tools/win32_oracle/
 * pf_harness_dispatch.h), called by the generic src_check.c.
 * pf_harness_dispatch_native() -- the same macro-bound world, but
 * dispatching to carrier/native/'s hand-written alternate-name forms
 * instead -- lives in the SEPARATE file icytower_harness_project_native.c,
 * not here: native_check.exe's build never links src/icytower/*.c, so a
 * dispatch function referencing update_frame()/is_solid()/etc. (this
 * file's own pf_harness_dispatch_src()) must not share a translation unit
 * with one native_check.exe actually links, or the linker would need to
 * resolve every extern this file references even though
 * pf_harness_dispatch_src() itself is never called there.
 *
 * notes/extraction_plan.md S3 calls this out by
 * name -- "the pointer-translation call sites for update_frame/is_solid's
 * ply/map arguments" -- as the project-specific residue once the wire
 * protocol/oracle-invocation mechanism moves to port_forge; this file is
 * that residue for every function this harness checks, not just those two:
 * the Icy function name table, and the couple of places a function reads a
 * pointer VALUE out of guest memory (not an argument, not the address of a
 * PF_MEM()-bound global) that the project's own generated bindings header
 * cannot reach.
 *
 * Hand-written harness plumbing (not generated), and NOT part of src/
 * itself: it is driver/plumbing, not recovered game semantics, and it is
 * fine for it to know about the harness's memory model the way src/ must
 * not.
 *
 * MEMORY MODEL:
 *
 * carrier/lift/harness/pf_bindings_harness.h (the --mem-macro PF_MEM twin
 * of carrier/gen/pf_bindings_src.h, both regenerated by gen_bindings.py,
 * not hand-edited -- see BINDINGS_NOTES.md) is force-included ahead of
 * src/icytower/*.c by build_src.cmd. It binds every game global those
 * files touch through PF_MEM() into pf_harness_mem.h's in-process copy of
 * the image (`pf_guest`).
 *
 * That seam alone is NOT enough for two entry points, and the src-form
 * dispatch below closes the remaining gap by hand at those two call sites
 * (tried first: identity-mapping the whole guest range with VirtualAlloc
 * at its real address, matching how the real carrier maps the image --
 * empirically ruled out: on this Windows build, VirtualQuery shows
 * 0x400000..0x800000 already densely occupied by loader/heap-manager
 * mappings before main() even runs, so a fixed VirtualAlloc there fails):
 *
 *   - is_solid's `m` parameter (and every other pointer-shaped vector
 *     ARGUMENT) arrives as a plain guest VA (matching what the real
 *     carrier would pass, since there a guest VA IS a valid host
 *     pointer); src/icytower/*.c dereferences it directly with no seam of
 *     its own (src/ has none -- that is the point of src/), so pf_tr()
 *     (port_forge/tools/win32_oracle/pf_harness_mem.h) translates it at
 *     the call site instead.
 *   - update_frame()/handle_player_collision_original() take no `ply`
 *     argument: they reach the active player through `ply[player_id]`, a
 *     pointer VALUE the vector generator stored inside guest memory
 *     itself (matching what the real carrier would have stored: a plain
 *     guest VA). Because that value lives in memory, not in an argument
 *     slot, pf_bindings_harness.h's per-global PF_MEM() cannot reach it --
 *     PF_MEM() only ever wraps the address of `ply` itself, not the
 *     pointer VALUE read back out of it at run time. This file performs
 *     the second translation by hand, overwriting that one slot with the
 *     equivalent host pointer immediately before calling into the
 *     function. The comparison domain compared afterwards never includes
 *     the ply[] slot itself, so leaving it translated for the rest of
 *     that dispatch call is harmless.
 *   - add_floor()/update_player() call get_demo() internally, which just
 *     relays the `demo` pointer VALUE verbatim (never dereferencing it
 *     itself) -- a caller that DOES dereference the result needs the same
 *     second translation, performed here for those two entry points.
 *
 * Both fixups are this file knowing where Icy Tower's OWN pointer-shaped
 * state lives (a fact already public in carrier/gen/it_globals.h and
 * notes/promotion_candidates.md) -- src/icytower/*.c itself stays exactly
 * as address-free as it is when compiled into the real carrier.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "it_types.h"
#include "pf_harness_mem.h"
#include "pf_harness_dispatch.h"

#define G_PLAYER_ID 0x4fe518u
#define G_PLY       0x4ff128u
#define G_DEMO      0x4dd250u
/* batch 9 (src/icytower/collision.c) */
#define G_SCREEN    0x4dda8cu      /* Allegro BITMAP *screen */
#define SCREEN_VTABLE_VA 0x7c3100u /* scratch GFX_VTABLE (icytower_specs.py) */
#define RAND_SEED_VA 0x794020u

extern void update_frame(void);
extern int  is_solid(Tmap *, int, int);
extern int  jump_player(Tplayer *, int);
extern void getFloorData(Tmap *, int, int *, int *, int *);
extern void reset_map(Tmap *);
extern void add_combo(Tgame_data *, Tgd_combo *);
extern int  line_intersect(int, int, int, int, int, int, int, int, int *, int *);
extern Tgamepad *get_gamepad(void);
