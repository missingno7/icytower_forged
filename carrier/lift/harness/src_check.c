/* src_check.c -- SRC-side driver of the offline equivalence check.
 *
 * Same wire protocol as native_check.c / lift_check.c (guest image in,
 * vector file in, result file out), calling the plain update_frame()/
 * is_solid() symbols compiled straight from src/icytower/ instead of
 * native_update_frame()/native_is_solid() or the generated lifted_<f>
 * ones, so lift_check.py's existing vector generation, unicorn oracle and
 * diff logic (carrier/lift/README.md SS7) can be reused unchanged -- only
 * --exe and --form point at this binary. See win32_pilot.md SS7a for what
 * this offline check verifies before src/'s forms are ever bound into the
 * running carrier.
 *
 * Hand-written harness (not generated), and NOT part of src/ itself: it is
 * driver/plumbing, not recovered game semantics, and it is fine for it to
 * know about the carrier's memory model the way src/ must not.
 *
 * MEMORY MODEL:
 *
 * carrier/gen/pf_bindings_harness.h (the --mem-macro PF_MEM twin of
 * carrier/gen/pf_bindings_src.h, both regenerated by gen_bindings.py, not
 * hand-edited -- see BINDINGS_NOTES.md) is force-included ahead of
 * src/icytower/update_frame.c and .../is_solid.c in build_src.cmd. It binds
 * every game global those files touch (reward_time, reward_scale,
 * player_id, ply, logic_count) through PF_MEM() into pf_harness_mem.h's
 * in-process copy of the image (`pf_guest`), exactly like the LIFTED and
 * NATIVE forms already do (build.cmd, build_native.cmd) -- this is the
 * single seam win32_pilot.md SS7a describes.
 *
 * That seam alone is NOT enough for these two functions, though, and this
 * driver closes the remaining gap by hand at the two call sites below
 * (tried first: identity-mapping the whole guest range with VirtualAlloc at
 * its real address, matching how the real carrier maps the image -- empirically
 * ruled out: on this Windows build, VirtualQuery shows 0x400000..0x800000
 * already densely occupied by loader/heap-manager mappings before main()
 * even runs, so a fixed VirtualAlloc there fails):
 *
 *   - is_solid's `m` parameter arrives as a plain guest VA in the vector
 *     (matching what the real carrier would pass, since there a guest VA
 *     IS a valid host pointer); is_solid.c dereferences it directly with no
 *     seam of its own (src/ has none -- that is the point of src/), so this
 *     driver translates it through PF_MEM() at the call site instead,
 *     exactly where carrier/native/native_is_solid.c's own PF_MEM(m) cast
 *     used to live before that translation moved out of the NATIVE form and
 *     into src/is_solid.c's caller.
 *   - update_frame() takes no argument: it reaches the active player through
 *     `ply[player_id]`, a pointer VALUE the vector generator stored inside
 *     guest memory itself (matching what the real carrier would have
 *     stored: a plain guest VA). Because that value lives in memory, not in
 *     an argument slot, pf_bindings_harness.h's per-global PF_MEM() cannot
 *     reach it -- PF_MEM() only ever wraps the address of `ply` itself, not
 *     the pointer VALUE read back out of it at run time. This driver
 *     performs the same second translation carrier/native/
 *     native_update_frame.c used to perform explicitly
 *     (`PF_MEM((unsigned int)(size_t)(*ply)[player_id])`), overwriting that
 *     one slot with the equivalent host pointer immediately before calling
 *     update_frame(). The domain compared afterwards (artifacts/
 *     src_equivalence.json) is reward_time/reward_scale/the Tplayer struct
 *     CONTENTS at PLAYER_VA, never the ply[] slot itself, so leaving the
 *     slot translated for the rest of that iteration is harmless.
 *
 * Both fixups are the harness knowing where the game's OWN pointer-shaped
 * state lives (a fact already public in carrier/gen/it_globals.h and
 * notes/promotion_candidates.md) -- src/icytower/*.c itself stays exactly
 * as address-free as it is when compiled into the real carrier.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

